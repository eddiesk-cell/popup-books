const DUCK = 0.4, HOLD_MS = 1500, BED = 0.28, FOLEY = 0.9, LOOP_PAD = 1;
// DUCK -8 dB while any voice speaks (DIRECTION.md says half = -6 dB), held 1.5 s after the last line. BED scales the director's layer gains:
// beds mix near -40 LUFS against narration at -27. Bed files carry LOOP_PAD seconds of the loop's own audio at both ends (AAC edge artefacts fall outside the loop).

// manifest for a book; `root` is the path from the page to web/ (e.g. "../" from web/live/)
// A book not in LIB declares itself in web/<book>/sfx/manifest.json { beds: [name], shots: [name], pools: { name: n } }: files <name>.m4a, <name>-2.m4a .. <name>-n.m4a
// (the same convention as POOLS). It is fetched here and merged into the returned object when it lands (`ready` resolves then; addSound re-asks for the beds wanted meanwhile).
export function manifestFor(book, root = "") {
  // an unknown book starts with no beds and only the sounds both books share, served from kapi's folder
  const known = !!LIB[book], dir = known ? book : "kapi", url = (d, n) => `${root}${d}/sfx/${n}.m4a`, beds = {}, sounds = {};
  const L = known ? LIB[book] : { beds: "", shots: LIB.kapi.shots.split(" ").filter(n => LIB.mali.shots.split(" ").includes(n)).join(" ") };
  for (const n of L.beds.split(" ").filter(Boolean)) beds[n] = url(dir, n);
  const pool = (d, n, c = POOLS[n] || 1) => [url(d, n), ...Array.from({ length: c - 1 }, (_, i) => url(d, `${n}-${i + 2}`))];
  const alias = () => { for (const [n, p] of Object.entries(ALIAS)) if (sounds[p]) sounds[n] = sounds[p]; };  // an authored name plays its pool
  for (const n of L.shots.split(" ")) sounds[n] = pool(dir, n);
  alias();
  const m = { beds, sounds };
  if (!known) m.ready = fetch(`${root}${book}/sfx/manifest.json`).then(r => r.ok ? r.json() : null).then(j => {
    if (!j) return;
    for (const n of j.beds ?? []) beds[n] = url(book, n);
    for (const n of j.shots ?? []) sounds[n] = pool(book, n, j.pools?.[n]);
    for (const [n, c] of Object.entries(j.pools ?? {})) sounds[n] = pool(book, n, c);
    alias();
  }).catch(() => {});  // no manifest: the book keeps the shared foley, as before
  return m;
}

// INTERACT: the tapped thing's name -> the pool that voices it (first match); a character or anything else is a paper card flick, pitched by its name
const KIND = [[/kite|sail|cloth|flag/, "i-cloth"], [/lantern|lamp|candle|flame|^lb[A-Z]/, "i-glow"], [/butterfl|moth|dragonfl|firefl|bat/, "i-wing"],
  [/wave|fish|splash/, "i-splash"], [/lilypad|water|river|backdrop|pool|ripple/, "i-water"], [/rock|stone|pebble|sandbank|islet|bridge/, "i-stone"],
  [/door|basket|stall|rope/, "i-creak"], [/fallen|jamun-fruit|fruit/, "i-fruit"], [/log|boat|village|market|house|screen|tree|branch|pole/, "i-wood"],
  [/reed|grass|fern|flower|hyacinth|petal|lotus|palm|leaf|leaves|nest|straw/, "i-leaf"]];
const SCALE = [1, 9 / 8, 5 / 4, 3 / 2, 5 / 3, 2, 9 / 4, 5 / 2];  // CORRECT: a pentatonic step up per right tap, so a game builds
const GAIN = { interact: 0.5, correct: 0.6, again: 0.45 };  // one level for every tap/game sound, whatever a page's foley table says
const semis = x => 2 ** (x / 12);

export function addSound(manifest, { reader, voices = [], ctx } = {}) {
  const AC = window.AudioContext || window.webkitAudioContext;
  if (!ctx) { try { ctx = new AC({ sampleRate: 22050 }); } catch { ctx = new AC(); } }  // 22 kHz halves the decoded memory
  const master = ctx.createGain(), duckG = ctx.createGain();
  duckG.connect(master); master.connect(ctx.destination);
  let step = 0, stepAt = 0, lastAt = 0; const lastOf = new Map(), queue = new Map();
  const buffers = {}, loading = {}, beds = {}, want = new Map(), warned = new Set(), bedUrls = new Set(Object.values(manifest.beds)); let lastBed = null;
  let muted = false;
  try { muted = localStorage.getItem("popup-sound") === "off"; } catch { /* private window: default on */ }
  master.gain.value = muted ? 0 : 1;

  // all fades run on the audio clock, so a slow render loop or a hidden tab cannot stall them
  const ramp = (param, v, tc) => { const t = ctx.currentTime; param.cancelScheduledValues(t); param.setValueAtTime(param.value, t); param.setTargetAtTime(v, t, tc); };
  const wake = () => { if (ctx.state !== "running") ctx.resume().catch(() => {}); };
  // iPad: WebKit unlocks audio on touchend/click, not pointerdown; keep trying until it runs
  for (const ev of ["pointerdown", "touchend", "click", "keydown"]) addEventListener(ev, wake, { capture: true, passive: true });
  document.addEventListener("visibilitychange", () => document.hidden ? ctx.suspend().catch(() => {}) : wake());

  // a failed or missing file warns once, is never cached as a failure, and resolves null instead of throwing
  const load = (url) => buffers[url] ? Promise.resolve(buffers[url]) : loading[url] ||
    (loading[url] = fetch(url).then(r => r.ok ? r.arrayBuffer() : Promise.reject(new Error("HTTP " + r.status)))
      .then(b => ctx.decodeAudioData(b)).then(b => (delete loading[url], buffers[url] = b))
      .catch(e => { delete loading[url]; if (!warned.has(url)) { warned.add(url); console.warn("sound: could not load", url, e?.message || e); } return null; }));

  // ducking: down fast when a voice starts; back up ~1.5 s after the last voice stops, so line gaps stay ducked
  const speaking = new Set(); let hold = 0, ducked = false;
  // failed: no next line is coming to hold the duck for, so the beds come straight back up (well within a second)
  // guard: a voice that said "play" and then died without an event (a rejected play(), a missing file) must not leave the beds ducked:
  // 2.5 s after ducking starts, and every 2.5 s after, if no voice is really playing the duck lifts
  let guard = 0; const all = [reader?.audio, ...voices].filter(Boolean), live = () => all.some(a => !a.paused && !a.ended && !a.error);
  const check = () => { if (!ducked) return; if (live()) guard = setTimeout(check, 2500); else { speaking.clear(); duck(false, true); } };
  const duck = (on, failed) => { ducked = !!on; clearTimeout(hold); clearTimeout(guard); if (on) { ramp(duckG.gain, DUCK, 0.08); guard = setTimeout(check, 2500); } else hold = setTimeout(() => ramp(duckG.gain, 1, failed ? 0.15 : 0.35), failed ? 0 : HOLD_MS); };
  const watch = (a) => {
    for (const ev of ["play", "playing"]) a.addEventListener(ev, () => { speaking.add(a); duck(true); });
    for (const ev of ["pause", "ended", "emptied", "error", "stalled", "abort"])  // a voice that fails or stalls mid-play lets the beds back up
      a.addEventListener(ev, () => { speaking.delete(a); if (!speaking.size) duck(false, /error|stalled|abort/.test(ev)); });
  };
  [reader?.audio, ...voices].forEach(a => a && watch(a));

  // the book's The End card is up (the viewer's #moral): the diorama under it is still, so no extra calls out; the bed stays, low.
  // shortcut: reads the viewer's element; take a flag from live.js if the card ever moves
  const theEnd = () => document.getElementById("moral")?.hidden === false;

  const release = (n) => { const b = beds[n]; if (!b || want.has(n)) return; try { b.src?.stop(); } catch { /* not started */ } b.g.disconnect(); delete beds[n]; };
  const api = {
    ctx, get muted() { return muted; }, get ducked() { return ducked; },
    load, buffers, duck,
    // one-shot from a pool: not the variant just heard, random pitch +-2 semitones and level +-2 dB (`exact`: the pitch is the caller's, as in a rising scale).
    // A pool loads on its first use, never at book open: the variant chosen plays at once, the rest are fetched behind it.
    log: [],
    play(name, { gain = 1, pitch = 1, exact = false, tag } = {}) {
      const urls = manifest.sounds[name]; if (!urls || muted || theEnd()) return Promise.resolve();
      wake();
      // a pool's plays are queued, so "not the one just heard" holds even for taps faster than a first-use fetch
      // the sparkle that rides every tap and game hit (moon-shimmer, asked for by the viewer) is dropped when a voice has just answered: one sound per touch, not two
      if (name === "moon-shimmer" && performance.now() - lastAt < 250) return Promise.resolve();
      const run = (queue.get(urls[0]) ?? Promise.resolve()).then(async () => {
        const last = lastOf.get(urls[0]), ready = urls.filter(u => buffers[u] && u !== last), fresh = urls.filter(u => u !== last);
        const pick = ready.length ? ready : fresh.length ? fresh : urls, url = pick[Math.floor(Math.random() * pick.length)];
        const buf = await load(url); urls.forEach(u => load(u)); if (!buf) return;
        lastOf.set(urls[0], url); lastAt = performance.now();
        const rate = exact ? pitch : pitch * semis(Math.random() * 4 - 2), lv = exact ? 1 : 10 ** ((Math.random() * 4 - 2) / 20);
        const s = ctx.createBufferSource(), g = ctx.createGain();
        s.buffer = buf; s.playbackRate.value = rate; g.gain.value = FOLEY * gain * lv;
        s.connect(g); g.connect(duckG); s.onended = () => { s.disconnect(); g.disconnect(); }; s.start();
        api.log.push({ name, file: url.split("/").pop(), rate: +rate.toFixed(3), gain: +g.gain.value.toFixed(3), tag }); if (api.log.length > 400) api.log.shift();
      }).catch(() => {});
      queue.set(urls[0], run); return run;
    },
    // the one hook live.js's foley(event, fallback) calls first: `authored` is the page's own [name, gain] for the event (or null). Returns true when it played.
    // Games: "game:miss" is TRY AGAIN, "game:won" and every other "game:*" is CORRECT (a step up the scale per hit, back to the bottom on a win, a new spread or 12 s of quiet).
    // Taps: "tap:<name>" is INTERACT: the page's own name when it has one (its pool), else a voice by the thing's kind.
    cue(ev, authored, fallback) {
      const [kind, ...rest] = ev.split(":"), who = rest.join(":"), now = performance.now();
      if (kind === "game") {
        if (who === "miss") return api.play("again", { gain: GAIN.again, tag: ev }), true;
        if (who === "won") { step = 0; return api.play("won", { gain: GAIN.correct, exact: true, tag: ev }), true; }
        if (now - stepAt > 12000) step = 0; stepAt = now;
        return api.play("ok", { gain: GAIN.correct, pitch: SCALE[Math.min(step++, SCALE.length - 1)], exact: true, tag: ev }), true;
      }
      if (kind !== "tap") return false;
      if (authored && !(ALIAS[authored[0]] === "i-paper")) return api.play(authored[0], { gain: GAIN.interact, tag: ev }), true;
      if (authored || fallback === "tap") {  // no sound of the page's own (or only the generic card): a voice by the thing's kind
        const h = [...who].reduce((a, c) => a * 31 + c.charCodeAt(0) >>> 0, 7), k = KIND.find(([re]) => re.test(who))?.[1];
        return api.play(k ?? "i-paper", { gain: GAIN.interact, pitch: k ? 1 : semis((h % 5) - 2), tag: ev }), true;
      }
      return false;
    },
    // layers: names or [name, gain]; they fade in (~2 s), every other bed fades out and is then stopped and freed.
    // `next` (optional) lists the following spread's beds: they are decoded ahead and kept, everything else is dropped.
    async setBed(layers, next = []) {
      lastBed = [layers, next];
      want.clear(); step = 0;
      for (const l of layers) { const [n, g = 0.3] = [].concat(l); want.set(n, g); }
      for (const [n, g] of want) {
        const url = manifest.beds[n]; if (!url) continue;
        let b = beds[n];
        if (!b) {
          b = beds[n] = { g: ctx.createGain(), src: null }; b.g.gain.value = 0; b.g.connect(duckG);
          load(url).then(buf => {
            if (!buf || beds[n] !== b) { if (!buf && beds[n] === b) delete beds[n]; return; }  // failed: retried on the next setBed
            const s = ctx.createBufferSource(); s.buffer = buf; s.loop = true;
            s.loopStart = LOOP_PAD; s.loopEnd = Math.max(LOOP_PAD + 0.1, buf.duration - LOOP_PAD);  // files carry 1 s of the loop's own audio each side
            s.connect(b.g); s.start(0, s.loopStart + Math.random() * (s.loopEnd - s.loopStart)); b.src = s;
          });
        }
        ramp(b.g.gain, g * BED, 0.7);
      }
      for (const n of Object.keys(beds)) if (!want.has(n)) { ramp(beds[n].g.gain, 0, 0.7); setTimeout(() => release(n), 4000); }
      const keep = new Set([...want.keys(), ...next].map(n => manifest.beds[n]));
      for (const u of bedUrls) if (!keep.has(u)) delete buffers[u];  // bounded memory: current + next spread only
      for (const n of next) if (manifest.beds[n]) load(manifest.beds[n]);
      wake();
    },
    mute(on) {
      muted = !!on; ramp(master.gain, muted ? 0 : 1, 0.05);
      try { localStorage.setItem("popup-sound", muted ? "off" : "on"); } catch { /* not remembered */ }
      if (!muted) wake();
    },
    update() {},  // kept for callers: everything now runs on the audio clock
    state: () => ({ duck: duckG.gain.value, mute: master.gain.value, beds: Object.fromEntries(Object.entries(beds).map(([n, b]) => [n, b.g.gain.value])) }),
  };
  manifest.ready?.then(() => { Object.values(manifest.beds).forEach(u => bedUrls.add(u)); if (lastBed) api.setBed(...lastBed); });  // beds asked for before the manifest landed start now
  return api;
}
